"""Markdown report for GitHub PR comments and job summaries.

Package names and snippets come from the (untrusted) pull request, so everything is
escaped: table cells cannot inject columns, rows or HTML, and code blocks cannot be
closed early.
"""

from __future__ import annotations

import re

from lockguard import __version__
from lockguard.models import RunReport, Severity
from lockguard.rules._common import sanitize

MARKER = "<!-- lockguard-report -->"
MAX_LENGTH = 60_000  # GitHub rejects comments over 65,536 characters
MAX_CLEAN_ROWS = 15
SNIPPET_LIMIT = 160

ICONS: dict[Severity, str] = {
    Severity.NONE: "✅",
    Severity.LOW: "🔵",
    Severity.MEDIUM: "🟡",
    Severity.HIGH: "🔴",
    Severity.CRITICAL: "🟥",
}

_CELL_ESCAPES = re.compile(r"([\\|`*_\[\]<>#~])")


def escape_cell(text: str) -> str:
    """Escape text for a Markdown table cell."""
    return _CELL_ESCAPES.sub(r"\\\1", sanitize(text).replace("\n", " ").replace("\r", " "))


def code_safe(text: str) -> str:
    """Make text safe inside a fenced code block (no fence can be closed early)."""
    return sanitize(text).replace("```", "ʼʼʼ").replace("\n", " ")


def _risk_cell(severity: Severity) -> str:
    label = severity.label if severity is Severity.NONE else f"**{severity.name}**"
    return f"{ICONS[severity]} {label}"


def render_markdown(report: RunReport, *, fail_on: Severity | None = None) -> str:
    """Render the report as GitHub-flavoured Markdown, starting with :data:`MARKER`."""
    verdict = report.verdict
    out: list[str] = [MARKER, f"## lockguard report - {report.headline()}", ""]

    packages = report.sorted_packages()
    if packages:
        out += ["| Package | Change | Risk | Findings |", "|---|---|---|---|"]
        flagged = [p for p in packages if p.findings]
        clean = [p for p in packages if not p.findings]
        shown_clean = clean if len(clean) <= MAX_CLEAN_ROWS else clean[: MAX_CLEAN_ROWS - 1]
        for pkg in [*flagged, *shown_clean]:
            rules = ", ".join(pkg.rule_ids()) or "-"
            out.append(
                f"| {escape_cell(pkg.change.name)} | {escape_cell(pkg.change.label)} | "
                f"{_risk_cell(pkg.risk)} | {escape_cell(rules)} |"
            )
        hidden = len(clean) - len(shown_clean)
        if hidden:
            out.append(f"| ... {hidden} more clean packages ... | | | |")
        out.append("")
    else:
        out += ["No registry packages changed.", ""]

    for pkg in packages:
        if not pkg.findings:
            continue
        out.append(f"### {escape_cell(pkg.change.name)}@{escape_cell(pkg.change.display_version)}")
        out.append("")
        out.append("```text")
        for finding in pkg.findings:
            location = f"{finding.location}  " if finding.location else ""
            out.append(
                code_safe(
                    f"[{finding.severity.label}]".ljust(11)
                    + finding.rule.ljust(21)
                    + location
                    + finding.message
                )
            )
            if finding.snippet:
                snippet = sanitize(finding.snippet)
                if len(snippet) > SNIPPET_LIMIT:
                    snippet = snippet[: SNIPPET_LIMIT - 1] + "..."
                out.append("           > " + code_safe(snippet))
        out.append("```")
        if pkg.ignored:
            out.append(f"_{pkg.ignored} finding(s) ignored by config._")
        out.append("")

    if report.skipped:
        out.append(f"<details><summary>Not analyzed ({len(report.skipped)})</summary>")
        out.append("")
        for entry in report.skipped:
            version = f"@{entry.version}" if entry.version else ""
            out.append(f"- {escape_cell(entry.name + version)} - {escape_cell(entry.reason)}")
        out.append("")
        out.append("</details>")
        out.append("")

    verdict_line = f"**Verdict:** {_risk_cell(verdict)}"
    if fail_on is not None:
        failed = verdict >= fail_on and verdict is not Severity.NONE
        verdict_line += f" - {'fails' if failed else 'passes'} the `{fail_on.label}` threshold"
    out.append(verdict_line)
    out.append("")
    out.append(
        f"<sub>Generated by lockguard {__version__}. Findings are heuristics: review the "
        "flagged code before merging.</sub>"
    )
    text = "\n".join(out) + "\n"
    if len(text) > MAX_LENGTH:
        head = text[: text.rfind("\n", 0, MAX_LENGTH - 200)]
        if head.count("```") % 2:
            head += "\n```"  # close the code block we cut through
        text = (
            head + "\n\n_Report truncated - run lockguard locally or see the job summary "
            "for the full output._\n"
        )
    return text
